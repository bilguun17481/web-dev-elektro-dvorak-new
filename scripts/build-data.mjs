/**
 * Builds the generated data files from the scraped export of the old site.
 *
 *   data/export/url_map.csv     11,196 product URLs with their old ids and ERP codes
 *   data/export/categories.json 389 categories with their old ids and names
 *
 * Outputs (never edited by hand):
 *   src/data/generated/redirects.json   old path to new path, for the 301 map
 *   src/data/generated/categories.json  the category list
 *   supabase/seed/0002_redirects.sql    the same redirects as the authoritative seed
 *
 * Run with `npm run data:build`.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(join(root, path), "utf8");

/** Minimal CSV reader: the export quotes any field containing a comma. */
function parseCsv(text) {
  const [header, ...lines] = text.trim().split("\n");
  const columns = header.split(",");
  return lines.map((line) => {
    const fields = [];
    let field = "";
    let quoted = false;
    for (const char of line) {
      if (char === '"') quoted = !quoted;
      else if (char === "," && !quoted) {
        fields.push(field);
        field = "";
      } else field += char;
    }
    fields.push(field);
    return Object.fromEntries(columns.map((name, i) => [name, fields[i] ?? ""]));
  });
}

const PRODUCT_PATH = /^\/([^/]+)\/pro(\d+)\.html$/;
const CATEGORY_URL = /^https:\/\/www\.elektrodvorak\.cz\/([^/]+)\/kat(\d+)\.html$/;

const rows = parseCsv(read("data/export/url_map.csv"));
const categories = JSON.parse(read("data/export/categories.json"));

/**
 * New product slugs come from the old ones, which are already clean and carry the
 * product name. 31 old slugs are shared by more than one product, so the lowest old id
 * keeps the bare slug and the others carry their old id. Deciding it by id rather than
 * by row order means a re-run produces the same slugs.
 */
const bySlug = new Map();
for (const row of rows) {
  const match = PRODUCT_PATH.exec(row.old_path);
  if (match === null) throw new Error(`unexpected product path: ${row.old_path}`);
  const [, slug] = match;
  bySlug.set(slug, [...(bySlug.get(slug) ?? []), row]);
}

const productSlugs = new Map();
let disambiguated = 0;
for (const [slug, group] of bySlug) {
  const ordered = [...group].sort((a, b) => Number(a.id) - Number(b.id));
  for (const [index, row] of ordered.entries()) {
    const unique = index === 0 ? slug : `${slug}-${row.id}`;
    if (index > 0) disambiguated += 1;
    productSlugs.set(row.old_path, unique);
  }
}

const redirects = {};
for (const row of rows) {
  redirects[row.old_path] = `/produkt/${productSlugs.get(row.old_path)}/`;
}

/**
 * 15 categories share 6 slugs between them: four separate "Ostatní", three
 * "Příslušenství", and so on. On the old site the kat id told them apart. They can only
 * be given meaningful slugs once their parents are known (`naradi/ostatni` rather than
 * `ostatni-176`), and the parent ids live in product_urls.json, which is missing from
 * the export. Until then the lowest old id keeps the bare slug and the rest carry their
 * id, which keeps every URL reachable and every redirect single-hop. `needsReslug`
 * marks them so the ones to revisit are a query, not a memory.
 */
const categoriesByOldId = new Map(
  Object.values(categories).map((entry) => {
    const match = CATEGORY_URL.exec(entry.url);
    if (match === null) throw new Error(`unexpected category url: ${entry.url}`);
    const [, slug, id] = match;
    return [Number(id), { oldId: Number(id), oldSlug: slug, name: entry.name }];
  }),
);

const categoriesByOldSlug = new Map();
for (const entry of categoriesByOldId.values()) {
  categoriesByOldSlug.set(entry.oldSlug, [...(categoriesByOldSlug.get(entry.oldSlug) ?? []), entry]);
}

const categoryList = [];
let reslugNeeded = 0;
for (const [oldSlug, group] of categoriesByOldSlug) {
  const ordered = [...group].sort((a, b) => a.oldId - b.oldId);
  for (const [index, entry] of ordered.entries()) {
    const slug = index === 0 ? oldSlug : `${oldSlug}-${entry.oldId}`;
    const needsReslug = group.length > 1;
    if (needsReslug) reslugNeeded += 1;
    categoryList.push({ oldId: entry.oldId, slug, name: entry.name, parentOldId: null, needsReslug });
    redirects[`/${oldSlug}/kat${entry.oldId}.html`] = `/kategorie/${slug}/`;
  }
}
categoryList.sort((a, b) => a.oldId - b.oldId);

const sql = [
  "-- Generated by scripts/build-data.mjs. Do not edit.",
  "-- The 301 map from the old site. Keyed on the old path, which the export proves unique.",
  "insert into redirects (shop_id, from_path, to_path, status)",
  "select s.id, v.from_path, v.to_path, 301",
  "from shops s, (values",
  Object.entries(redirects)
    .map(([from, to]) => `  ('${from.replace(/'/g, "''")}', '${to.replace(/'/g, "''")}')`)
    .join(",\n"),
  ") as v(from_path, to_path)",
  "where s.slug = 'elektrodvorak'",
  "on conflict (shop_id, from_path) do update set to_path = excluded.to_path;",
].join("\n");

mkdirSync(join(root, "src/data/generated"), { recursive: true });
mkdirSync(join(root, "supabase/seed"), { recursive: true });
writeFileSync(join(root, "src/data/generated/redirects.json"), `${JSON.stringify(redirects, null, 0)}\n`);
writeFileSync(join(root, "src/data/generated/categories.json"), `${JSON.stringify(categoryList, null, 1)}\n`);
writeFileSync(join(root, "supabase/seed/0002_redirects.sql"), `${sql}\n`);

const productRedirects = rows.length;
const categoryRedirects = categoryList.length;
console.log(`products          ${productRedirects}`);
console.log(`  slugs kept      ${productRedirects - disambiguated}`);
console.log(`  slugs suffixed  ${disambiguated} (old slug shared by more than one product)`);
console.log(`categories        ${categoryRedirects}`);
console.log(`  need reslug     ${reslugNeeded} (slug shared, parent unknown until product_urls.json)`);
console.log(`redirects total   ${Object.keys(redirects).length}`);
